from django.db import models
from PlanningApp.models import Simulation
import json


class SimulationResults(models.Model):
    """
    Stores the results of a simulation calculation.
    
    This model stores aggregated metrics and detailed timestep data
    from simulating a production plan with generation and price data.
    """
    
    simulation = models.OneToOneField(
        Simulation,
        on_delete=models.CASCADE,
        related_name='results',
        help_text="The simulation these results belong to"
    )
    
    # Aggregated metrics
    total_electricity_used_kWh = models.FloatField(
        help_text="Total electricity consumed during the simulation (kWh)"
    )
    
    grid_electricity_purchased_kWh = models.FloatField(
        help_text="Total electricity purchased from the grid (kWh)"
    )
    
    solar_generated_kWh = models.FloatField(
        default=0,
        help_text="Total electricity generated by solar panels (kWh)"
    )
    
    cogen_generated_kWh = models.FloatField(
        default=0,
        help_text="Total electricity generated by cogenerator (kWh)"
    )
    
    wasted_energy_kWh = models.FloatField(
        default=0,
        help_text="Total generated electricity that was wasted (kWh)"
    )
    
    # For dual-plan simulations store both costs explicitly
    original_cost_euros = models.FloatField(
        default=0,
        help_text="Total cost (EUR) for the non-optimized plan"
    )
    optimized_cost_euros = models.FloatField(
        default=0,
        help_text="Total cost (EUR) for the optimized plan"
    )
    # Deprecated/legacy: may reflect a single-plan run; prefer the fields above
    total_cost_euros = models.FloatField(
        help_text="[Deprecated] Total cost for single-plan simulations (EUR)",
        null=True,
        blank=True
    )
    
    total_co2_kg = models.FloatField(
        default=0,
        help_text="Total CO2 emissions (kg)"
    )
    
    # Detailed timestep data (stored as JSON)
    timestep_data = models.JSONField(
        default=dict,
        help_text="Detailed timestep-by-timestep data (timestamps, demand, generation, costs)"
    )
    
    # Metadata
    calculated_at = models.DateTimeField(
        auto_now_add=True,
        help_text="When this simulation was calculated"
    )
    
    timestep_minutes = models.IntegerField(
        default=5,
        help_text="Timestep interval used in the simulation (minutes)"
    )
    
    num_timesteps = models.IntegerField(
        default=0,
        help_text="Total number of timesteps in the simulation"
    )
    
    class Meta:
        verbose_name = "Simulation Result"
        verbose_name_plural = "Simulation Results"
        ordering = ['-calculated_at']
    
    def __str__(self):
        return f"Results for {self.simulation.name}"
    
    def get_timestep_summary(self):
        """Return a summary of timestep data"""
        if not self.timestep_data:
            return {}
        
        return {
            'num_timesteps': len(self.timestep_data.get('timestamps', [])),
            'timestep_minutes': self.timestep_minutes,
            'total_demand_kWh': sum(self.timestep_data.get('total_demand_kWh', [])),
            'total_generation_kWh': sum(self.timestep_data.get('total_generation_kWh', [])),
        }
