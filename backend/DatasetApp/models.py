from django.db import models
from django.core.validators import MinValueValidator


class TemperatureDataset(models.Model):
    """Hourly timetable for temperature data."""
    is_active = models.BooleanField(default=False, help_text="Only one can be true in the system")
    name = models.CharField(max_length=255, unique=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)
    
    class Meta:
        ordering = ['-created_at']
    
    def save(self, *args, **kwargs):
        if self.is_active:
            # Deactivate all other datasets
            TemperatureDataset.objects.filter(is_active=True).exclude(pk=self.pk).update(is_active=False)
        super().save(*args, **kwargs)
    
    def __str__(self):
        return f"{self.name}"


class TemperatureRecord(models.Model):
    """Temperature record for a specific timestamp."""
    temperature_dataset = models.ForeignKey(
        TemperatureDataset,
        on_delete=models.CASCADE,
        related_name='records'
    )
    timestamp = models.DateTimeField()
    outside_temperature = models.FloatField(help_text="Temperature in Celsius")
    
    class Meta:
        ordering = ['timestamp']
        unique_together = ['temperature_dataset', 'timestamp']
    
    def __str__(self):
        return f"{self.temperature_dataset.name} - {self.timestamp}"


